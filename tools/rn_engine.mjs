// Writes rn/src/engine.gen.js: the web app's own engine (app/engine.js), the row shaping (app/shape.js) and the
// collector's rules (collector/money-collector.gs) as one module for the React Native app, so the phone app works out
// every figure with exactly the same code as the website (no second copy of the maths).
// Also writes rn/src/config.json from app/public-config.json (public by design), and copies the made-up demo data
// (tools/demo/demo-fixture.json) for the demo build.
//
//   node tools/rn_engine.mjs          write both files
//   node tools/rn_engine.mjs --check  fail if either file is out of date
//
// makeEngine(env) gives a fresh engine. env: {window, localStorage, document}. It returns every top-level name of
// engine.js as a live getter (so `e.TX` is always the current list), plus shapeData and shapeEdits.
import fs from "fs";
import path from "path";
import url from "url";
import { createRequire } from "module";

const ROOT = path.resolve(path.dirname(url.fileURLToPath(import.meta.url)), "..");
const require = createRequire(path.join(ROOT, "rn/package.json"));
const acorn = require("acorn");

const read = (p) => fs.readFileSync(path.join(ROOT, p), "utf8");
const engine = read("app/engine.js") + "\n" + read("app/trips.js") + "\n" + read("app/rewards.js"), shape = read("app/shape.js"), gs = read("collector/money-collector.gs");
const refine = "/* from collector/money-collector.gs */\n" + gs.slice(gs.indexOf("var RULES = ["), gs.indexOf("var HEADERS = [")) + "\n" +
  gs.slice(gs.indexOf("function num_(s)"), gs.indexOf("/** Reads a message once"));

// every name engine.js declares at the top level
const names = [];
for (const node of acorn.parse(engine, { ecmaVersion: "latest", sourceType: "script" }).body) {
  if (node.type === "FunctionDeclaration") names.push(node.id.name);
  else if (node.type === "VariableDeclaration") node.declarations.forEach((d) => { if (d.id.type === "Identifier") names.push(d.id.name); });
  else if (node.type === "ClassDeclaration") names.push(node.id.name);
}
const getters = names.map((n) => `    get ${n}() { return ${n}; },`).join("\n");

const src = `// GENERATED by tools/rn_engine.mjs from app/engine.js, app/trips.js, app/rewards.js, app/shape.js and collector/money-collector.gs.
// Do not edit: change those files and run node tools/rn_engine.mjs.
/* eslint-disable */
export function makeEngine(env) {
  const { window, localStorage, document } = env;
  const MONEY = window.MONEY;
  // the collector's rules and the row shaping keep their own scope, as in the web app (the engine has its own NOT_SPENDING)
  const { shapeData, shapeEdits } = (() => {
${refine}
${shape}
  return { shapeData, shapeEdits };
  })();
${engine}
  return {
    shapeData, shapeEdits,
${getters}
  };
}
`;

// the server's copy (supabase/functions/_shared/engine.gen.js): the engine, the row shaping and the collector's rules
// as one module, so the server works out the widget numbers and the 9 PM summary with the app's own code
const server = "// GENERATED by tools/rn_engine.mjs from app/engine.js, app/shape.js and collector/money-collector.gs.\n" +
  "// Do not edit: change those files and run node tools/rn_engine.mjs.\n" +
  "// makeEngine({Date}) gives a fresh copy of the engine; pass istDate() from ist-date.js so local time is India's.\n" +
  "export function makeEngine(env) {\n" +
  "  const { Date } = env;\n" +
  "  const window = { MONEY: null, UI: null }, MONEY = null;\n" +
  "  const localStorage = { getItem: () => null, setItem() {}, removeItem() {} };\n" +
  "  const document = { hidden: true, getElementById: () => null, addEventListener() {},\n" +
  "    createElement: () => ({ textContent: \"\", get innerHTML() { return String(this.textContent).replace(/&/g, \"&amp;\").replace(/</g, \"&lt;\").replace(/>/g, \"&gt;\"); } }) };\n" +
  "  // the collector's rules and the row shaping keep their own scope (the engine has its own NOT_SPENDING)\n" +
  "  const { shapeData, shapeEdits } = (() => {\n" + refine + "\n" + shape + "\n  return { shapeData, shapeEdits };\n  })();\n" +
  read("app/engine.js") +
  "\n  return { shapeData, shapeEdits, ingest, widgetModel, digestModel, snapshot };\n}\n";

const cfg = JSON.parse(read("app/public-config.json"));
const conf = JSON.stringify({ SUPABASE_URL: cfg.SUPABASE_URL, SUPABASE_PUBLISHABLE_KEY: cfg.SUPABASE_PUBLISHABLE_KEY, VAPID_PUBLIC_KEY: cfg.VAPID_PUBLIC_KEY }, null, 2) + "\n";

const outs = [["rn/src/engine.gen.js", src], ["supabase/functions/_shared/engine.gen.js", server], ["rn/src/config.json", conf], ["rn/src/demo-fixture.json", read("tools/demo/demo-fixture.json")]];
if (process.argv.includes("--check")) {
  const stale = outs.filter(([p, s]) => !fs.existsSync(path.join(ROOT, p)) || fs.readFileSync(path.join(ROOT, p), "utf8") !== s);
  if (stale.length) { console.error("out of date: " + stale.map((x) => x[0]).join(", ") + " (run node tools/rn_engine.mjs)"); process.exit(1); }
  console.log("rn engine up to date");
} else {
  for (const [p, s] of outs) { fs.mkdirSync(path.dirname(path.join(ROOT, p)), { recursive: true }); fs.writeFileSync(path.join(ROOT, p), s); }
  console.log("wrote rn/src/engine.gen.js (" + names.length + " names) and rn/src/config.json");
}
